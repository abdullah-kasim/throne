export const SPEC_FILE_LINE_LIMIT = 300;

export const FEATURE_MAP_FILE_NAME = "FEATURE_MAP.md";
export const INDEX_FILE_NAME = "README.md";
export const ERRATA_FILE_NAME = "ERRATA.md";
export const FILES_THAT_ARE_NOT_SPECS: readonly string[] = [FEATURE_MAP_FILE_NAME, INDEX_FILE_NAME, ERRATA_FILE_NAME];

export const NAME_PREFIX = "# ";
export const SUMMARY_LABEL = "Summary: ";
export const CODE_LABEL = "Code: ";
export const SEARCH_WORDS_LABEL = "Search words: ";

export const SUB_FEATURES_SECTION = "## Sub-features";
export const FIXED_SECTIONS: readonly string[] = [
  "## What it does",
  SUB_FEATURES_SECTION,
  "## How to reach it and prove it works",
  "## Gotchas",
];

export const FEATURE_MAP_FIRST_LINES: readonly string[] = [
  "# Feature map",
  "",
  "Generated by `throne feature-map` from the spec file headers. Do not edit it by hand; run the command again.",
];

export const GENERAL_AREA = "general";

export function looksLikeThroneSpecFile(content: string): boolean {
  const [name, summary, code, searchWords] = content.split("\n");
  return (
    name?.startsWith(NAME_PREFIX) === true &&
    summary?.startsWith(SUMMARY_LABEL) === true &&
    code?.startsWith(CODE_LABEL) === true &&
    searchWords?.startsWith(SEARCH_WORDS_LABEL) === true
  );
}

export function looksLikeThroneFeatureMap(content: string): boolean {
  return content.split("\n").slice(0, FEATURE_MAP_FIRST_LINES.length).join("\n") === FEATURE_MAP_FIRST_LINES.join("\n");
}
